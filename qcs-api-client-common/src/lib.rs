/// The docstring for the `qcs_api_client_common` Python package.
///
/// Both `__init__.py` files in the package are generated by `pyo3_stub_gen`, which does not
/// write docstrings into them, so this is the only definition of the package docstring:
/// [`init_module`] assigns it to the package at import time, and `module_doc!` copies it into
/// the generated type stubs.
#[cfg(feature = "python")]
const PACKAGE_DOC: &str = "A suite of common functionalities for QCS client applications.

This package offers reusable middleware implementations
that can be integrated into various client libraries.
This allows for consistent behavior across different projects
and facilitates easier maintenance and scalability of client-side logic.

⚠️ This package is still in early development
and breaking changes should be expected between minor versions.
";

#[cfg(feature = "python")]
#[pymodule]
#[pyo3(name = "_qcs_api_client_common")]
fn init_module(m: &Bound<'_, PyModule>) -> PyResult<()> {
    let py = m.py();
    init_submodule("qcs_api_client_common._qcs_api_client_common", py, m)?;

    m.setattr("__doc__", PACKAGE_DOC)?;

    Ok(())
}

#[cfg(feature = "stubs")]
mod stubs {
    use pyo3_stub_gen::{module_doc, reexport_module_members};

    // During stub generation, these `qcs_api_client_common._qcs_api_client_common` modules and
    // their contents will be re-exported into the `qcs_api_client_common` namespace, and the
    // corresponding `__init__.py` files will be generated.
    reexport_module_members!("qcs_api_client_common" from "qcs_api_client_common._qcs_api_client_common"; *, "__doc__");
    reexport_module_members!(
        "qcs_api_client_common.configuration" from "qcs_api_client_common._qcs_api_client_common.configuration"
    );

    // The pure-Python modules are unknown to `pyo3_stub_gen`, so re-export them into the
    // top-level namespace explicitly. Naming the package as its own source module is
    // deliberate: it generates `from qcs_api_client_common import grpc, httpx`, which resolves
    // the submodules through the partially-initialized package in `sys.modules`.
    reexport_module_members!("qcs_api_client_common" from "qcs_api_client_common"; "grpc", "httpx");

    module_doc!(
        "qcs_api_client_common._qcs_api_client_common",
        "{}",
        crate::PACKAGE_DOC
    );
}

#[cfg(feature = "stubs")]
pyo3_stub_gen::define_stub_info_gatherer!(stub_info);
